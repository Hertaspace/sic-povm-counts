def make_program():
    program, source = A.make_program("6a")
    prefix = program[:-len(A.COMMON)]
    seen, pairs = set(), []
    for r in range(6):
        for s in range(6):
            key = min((r,s),(s,r),(-r % 6,-s % 6),(-s % 6,-r % 6))
            if key not in seen:
                seen.add(key)
                pairs.append([r,s])
    names, gens, trace = C.coefficients(6)
    if len(names)!=12 or len(gens)!=13:
        raise ValueError("e01 d6 is no longer the expected 14 by 12 system")
    representatives=axes()
    headers="CASES="+json.dumps(pairs,separators=(",",":"))+";\nAXES="+json.dumps(representatives,separators=(",",":"))+";\n"
    return prefix+headers+BODY,source,names,gens+["t*y-1"],representatives


