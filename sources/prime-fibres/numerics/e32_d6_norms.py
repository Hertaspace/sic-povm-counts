def axes():
    canon = lambda v: min(v, tuple((-x) % 6 for x in v))
    found = {canon((0, 1)): ("", (0, 1))}
    queue = deque([("", (0, 1))])
    while queue:
        word, (a, b) = queue.popleft()
        for letter, vector in (("F", (b % 6, -a % 6)), ("S", (a, (b-a) % 6))):
            key = canon(vector)
            if key not in found:
                item = (word+letter, vector)
                found[key] = item
                queue.append(item)
    all_lines = {canon((a, b)) for a in range(6) for b in range(6) if gcd(gcd(a, b), 6) == 1}
    if set(found) != all_lines or len(found) != 12:
        raise ValueError("F,S BFS did not exhaust exactly twelve primitive axes")
    return [[word, list(vector)] for word, vector in found.values()]


